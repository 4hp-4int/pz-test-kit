#!/usr/bin/env python3
"""Emit TextureSizes.lua -- real sub-texture dimensions for the UIMock.

WHY THIS EXISTS

UIMock's getTexture used to hand back a stub claiming 32x32 for every texture
in the game. Nothing checked it, because most draw calls pass an explicit
destination rect and never ask. But any code that TILES, or fits, or steps by
the source size reads getWidth()/getHeight() -- and got 32.

That is not a cosmetic inaccuracy, it is a preview that cannot see a whole
class of bug. Measured case: VorpallySauced's journal tiled a 512x512 paper
texture across an 846px sheet and squashed the 334px remainder, which put a
false crease down the page beside the real fold. In the preview the same code
tiled at 32px, so the remainder was 13px and invisible. The preview rendered
one fold, the game rendered two, and the preview was the thing being trusted.

Sizes come from the same .pack files the game loads, so there is no second
source of truth to drift.

    python tools/gen_texture_sizes.py <root> [<root> ...]

Writes media/lua/client/UIView/TextureSizes.lua relative to this file's parent.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import unpack_textures  # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "media", "lua", "client", "UIView", "TextureSizes.lua")


def collect(roots):
    sizes = {}
    packs = 0
    for root in roots:
        tpdir = os.path.join(root, "media", "texturepacks")
        if not os.path.isdir(tpdir):
            continue
        for fn in sorted(os.listdir(tpdir)):
            if not fn.endswith(".pack"):
                continue
            try:
                pk = unpack_textures.Pack(os.path.join(tpdir, fn))
            except Exception as exc:
                print("  [skip] %s: %s" % (fn, exc), file=sys.stderr)
                continue
            packs += 1
            for page in pk.pages:
                for sub in page["sub"]:
                    # fx/fy are the ORIGINAL (pre-trim) dimensions when the
                    # packer trimmed transparent margins; w/h are what actually
                    # got stored. getWidth() reports the original, which is what
                    # layout code is reasoning about.
                    w = sub.get("fx") or sub["w"]
                    h = sub.get("fy") or sub["h"]
                    prev = sizes.get(sub["name"])
                    if prev and prev != (w, h):
                        print("  [warn] %s: %s disagrees with %s"
                              % (sub["name"], (w, h), prev), file=sys.stderr)
                    sizes[sub["name"]] = (w, h)
    return sizes, packs


def main():
    roots = sys.argv[1:]
    if not roots:
        print("usage: gen_texture_sizes.py <root> [<root> ...]", file=sys.stderr)
        return 2
    sizes, packs = collect(roots)

    lines = [
        "-- GENERATED by uiview/tools/gen_texture_sizes.py -- do not edit.",
        "--",
        "-- Real sub-texture dimensions, read from the same .pack files the game",
        "-- loads. UIMock's getTexture returns these so that code which tiles or",
        "-- steps by the source size behaves in the preview the way it does in",
        "-- game. A hardcoded 32x32 stub made tiling artifacts invisible here",
        "-- while they were plainly visible on screen.",
        "--",
        "-- %d texture(s) from %d pack(s)." % (len(sizes), packs),
        "",
        "return {",
    ]
    for name in sorted(sizes):
        w, h = sizes[name]
        lines.append('    ["%s"] = { %d, %d },' % (name, w, h))
    lines += ["}", ""]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("[gen_texture_sizes] %d texture(s) from %d pack(s) -> %s"
          % (len(sizes), packs, os.path.relpath(OUT, HERE)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
