#!/usr/bin/env python3
"""Parse PZ's real craftRecipe scripts into a Lua fixture for the test kit.

The kit runs Kahlua (Lua), not PZ's Java ScriptManager, so it can't load real
CraftRecipe objects. But the recipes ARE text. This extracts each craftRecipe's
shape — category, tags, inputs (items/tags/tool/mapper/amount), outputs
(item/mapper/amount), and the itemMappers (result list + default) — and emits a Lua
table. RecipeDB.installReal() wraps those in mock recipe objects, so our real
resolver/category/family logic can be swept over the ACTUAL B42 corpus.

Regenerate after a PZ update (ties to CERTIFICATION.md):
    python tools/parse_recipes.py > uiview/media/lua/client/UIView/RealRecipes.lua
"""
import re, sys, glob, os

PZ = os.environ.get("PZ_INSTALL_DIR",
    r"C:\Program Files (x86)\Steam\steamapps\common\ProjectZomboid")
RECIPE_GLOB = os.path.join(PZ, "media", "scripts", "generated", "recipes", "*.txt")


def find_blocks(text, keyword):
    """Yield (name, body) for every `<keyword> Name { ... }` (brace-matched)."""
    i = 0
    pat = re.compile(r'\b' + keyword + r'\s+([A-Za-z0-9_]+)\s*\{')
    while True:
        m = pat.search(text, i)
        if not m:
            return
        name = m.group(1)
        depth, j = 1, m.end()
        while j < len(text) and depth:
            c = text[j]
            if c == '{': depth += 1
            elif c == '}': depth -= 1
            j += 1
        yield name, text[m.end():j - 1]
        i = j


def sub_block(body, keyword):
    """The brace body of a nested `keyword { ... }` (e.g. inputs/outputs), or ''."""
    m = re.search(r'\b' + keyword + r'\s*\{', body)
    if not m:
        return ''
    depth, j = 1, m.end()
    while j < len(body) and depth:
        if body[j] == '{': depth += 1
        elif body[j] == '}': depth -= 1
        j += 1
    return body[m.end():j - 1]


def split_items(s):
    """`Base.A;2:Base.B;Base.C` -> ['Base.A','Base.B','Base.C'] (drop count prefix)."""
    out = []
    for part in s.split(';'):
        part = part.strip()
        if not part:
            continue
        if ':' in part:
            part = part.split(':', 1)[1].strip()   # strip a `2:` count prefix
        out.append(part)
    return out


def parse_input(line):
    line = line.strip().rstrip(',')
    if not line.startswith('item'):
        return None                                # skip fluid/energy inputs
    inp = {'amount': 1, 'items': [], 'tags': [], 'tool': False, 'mappers': []}
    m = re.match(r'item\s+(\d+)', line)
    if m:
        inp['amount'] = int(m.group(1))
    m = re.search(r'(?<![A-Za-z])\[([^\]]*)\]', line)   # standalone item list (NOT tags[/mappers[/flags[)
    if m:
        inp['items'] = split_items(m.group(1))
    m = re.search(r'tags\[([^\]]*)\]', line)
    if m:
        inp['tags'] = [t.strip() for t in m.group(1).split(';') if t.strip()]
    m = re.search(r'mappers\[([^\]]*)\]', line)
    if m:
        inp['mappers'] = [t.strip() for t in m.group(1).split(';') if t.strip()]
    if 'mode:keep' in line or 'flags[Tool' in line:
        inp['tool'] = True
    return inp


def parse_output(line):
    line = line.strip().rstrip(',')
    if not line.startswith('item'):
        return None                                # skip fluid/energy outputs
    out = {'amount': 1, 'item': None, 'mapper': None}
    m = re.match(r'item\s+(\d+)', line)
    if m:
        out['amount'] = int(m.group(1))
    m = re.search(r'mapper:([A-Za-z0-9_]+)', line)
    if m:
        out['mapper'] = m.group(1)
    else:
        rest = re.sub(r'^item\s+\d+\s*', '', line)
        rest = re.sub(r'flags\[[^\]]*\]', '', rest).strip()
        if rest and not rest.startswith('['):
            out['item'] = rest.split()[0]
    return out


def parse_mappers(body):
    mappers = {}
    for name, mbody in find_blocks(body, 'itemMapper'):
        results, default = [], None
        for line in mbody.splitlines():
            line = line.strip().rstrip(',')
            if '=' not in line:
                continue
            lhs, rhs = [x.strip() for x in line.split('=', 1)]
            if lhs == 'default':
                default = rhs
            elif lhs.startswith('Base.') or '.' in lhs:
                results.append(lhs)                # lhs = an OUTPUT result item
        seen, uniq = set(), []
        for r in results:
            if r not in seen:
                seen.add(r); uniq.append(r)
        mappers[name] = {'results': uniq, 'default': default}
    return mappers


def lua_str(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def lua_list(xs):
    return '{' + ', '.join(lua_str(x) for x in xs) + '}'


def emit(recipes):
    print("-- GENERATED by tools/parse_recipes.py from the real PZ recipe scripts.")
    print("-- Do not edit by hand; regenerate after a PZ update (see CERTIFICATION.md).")
    print("return {")
    for r in recipes:
        print("  { name=%s, category=%s, tags=%s," % (
            lua_str(r['name']), lua_str(r['category']), lua_list(r['tags'])))
        ins = []
        for i in r['inputs']:
            ins.append("{amount=%d, tool=%s, items=%s, tags=%s, mappers=%s}" % (
                i['amount'], 'true' if i['tool'] else 'false',
                lua_list(i['items']), lua_list(i['tags']), lua_list(i['mappers'])))
        print("    inputs={%s}," % ', '.join(ins))
        outs = []
        for o in r['outputs']:
            item = lua_str(o['item']) if o['item'] else 'nil'
            mapper = lua_str(o['mapper']) if o['mapper'] else 'nil'
            outs.append("{amount=%d, item=%s, mapper=%s}" % (o['amount'], item, mapper))
        print("    outputs={%s}," % ', '.join(outs))
        mp = []
        for name, m in r['mappers'].items():
            d = lua_str(m['default']) if m['default'] else 'nil'
            mp.append("%s={results=%s, default=%s}" % (
                name if re.match(r'^[A-Za-z_]\w*$', name) else '[' + lua_str(name) + ']',
                lua_list(m['results']), d))
        print("    mappers={%s} }," % ', '.join(mp))
    print("}")


def main():
    recipes = []
    for path in sorted(glob.glob(RECIPE_GLOB)):
        text = open(path, encoding='utf-8', errors='replace').read()
        for name, body in find_blocks(text, 'craftRecipe'):
            cat = re.search(r'\bcategory\s*=\s*([A-Za-z]+)', body)
            tags = re.search(r'\bTags\s*=\s*([A-Za-z0-9_;]+)', body)
            inputs = [parse_input(l) for l in sub_block(body, 'inputs').split(',')]
            outputs = [parse_output(l) for l in sub_block(body, 'outputs').split(',')]
            recipes.append({
                'name': name,
                'category': cat.group(1) if cat else 'Other',
                'tags': [t for t in (tags.group(1).split(';') if tags else []) if t],
                'inputs': [i for i in inputs if i],
                'outputs': [o for o in outputs if o],
                'mappers': parse_mappers(body),
            })
    sys.stderr.write("parsed %d recipes\n" % len(recipes))
    emit(recipes)


if __name__ == "__main__":
    main()
